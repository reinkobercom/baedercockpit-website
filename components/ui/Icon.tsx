import {
  Activity,
  BadgeCheck,
  Bell,
  CalendarDays,
  ClipboardList,
  Coffee,
  Coins,
  Droplets,
  FileCheck,
  FileSpreadsheet,
  Gauge,
  HeartHandshake,
  Heart,
  KeyRound,
  Landmark,
  Layers,
  LayoutDashboard,
  MessageCircle,
  NotebookPen,
  Play,
  Plug,
  Repeat,
  Server,
  Settings2,
  ShieldCheck,
  Smartphone,
  Users,
  Waves,
  type LucideIcon,
} from "lucide-react";

const map: Record<string, LucideIcon> = {
  activity: Activity,
  badge: BadgeCheck,
  bell: Bell,
  calendar: CalendarDays,
  clipboard: ClipboardList,
  coffee: Coffee,
  coins: Coins,
  dashboard: LayoutDashboard,
  droplets: Droplets,
  filecheck: FileCheck,
  gauge: Gauge,
  handshake: HeartHandshake,
  heart: Heart,
  key: KeyRound,
  landmark: Landmark,
  layers: Layers,
  message: MessageCircle,
  notebook: NotebookPen,
  play: Play,
  plug: Plug,
  repeat: Repeat,
  server: Server,
  settings: Settings2,
  sheet: FileSpreadsheet,
  shield: ShieldCheck,
  smartphone: Smartphone,
  users: Users,
  waves: Waves,
};

export function Icon({ name, size = 22, className = "" }: { name: string; size?: number; className?: string }) {
  const C = map[name] ?? Waves;
  return <C size={size} strokeWidth={1.75} className={className} aria-hidden />;
}
